"""Code generation: turns the checked, annotated AST into Python source code.

The tree has already passed every check, so this phase never reports errors
in the FlowLang program. It walks the tree once more and writes Python, one
method per kind of node (tree-walking code generation).

Most constructs translate directly (see docs/language.md, section 4). These
are the places where FlowLang and Python differ, and how each one is handled:

  1. Blocks:       Python uses indentation, so the generator tracks an indent
                   level, and writes `pass` for an empty block.
  2. Division:     int / int is integer division in FlowLang, so it becomes //.
                   This uses the types that semantic analysis stored in the tree.
  3. Precedence:   Python's `not` binds looser than `==`, and Python chains
                   comparisons (a < b == c). Parentheses are added where Python
                   would otherwise read the expression differently.
  4. Globals:      a function that assigns a global variable needs a `global`
                   line in Python, from the analysis's global_writes.
  5. Names:        FlowLang names that are Python keywords (or names the output
                   relies on, like print) get a trailing underscore.
  6. int -> float: a value widened to float is converted, so 2 becomes 2.0.
"""

import keyword

from flowlang.ast_nodes import (
    Assign, BinaryOp, Block, Call, CallStmt, EmitStmt, EventDecl, Expression,
    FunctionDecl, IfStmt, Literal, Program, RepeatStmt, ReturnStmt, Statement,
    TriggerStmt, UnaryOp, VarDecl, Variable,
)
from flowlang.semantic import AnalysisResult

INDENT = "    "

PYTHON_TYPES = {"int": "int", "float": "float", "bool": "bool", "string": "str"}

# Names that would clash with Python keywords or with names the generated code uses.
RESERVED_NAMES = set(keyword.kwlist) | {
    "print", "int", "float", "str", "bool", "range", "_", "__name__",
}

# Python precedence levels: a higher number binds tighter.
OR, AND, NOT, COMPARISON, ADDITIVE, MULTIPLICATIVE, NEGATE, POWER, ATOM = range(1, 10)

BINARY_PRECEDENCE = {
    "||": OR,
    "&&": AND,
    "==": COMPARISON, "!=": COMPARISON, "<": COMPARISON, ">": COMPARISON,
    "<=": COMPARISON, ">=": COMPARISON,
    "+": ADDITIVE, "-": ADDITIVE,
    "*": MULTIPLICATIVE, "/": MULTIPLICATIVE, "%": MULTIPLICATIVE,
    "^": POWER,
}

PYTHON_OPERATORS = {"&&": "and", "||": "or", "^": "**"}  # the rest are written the same

BUILTINS_CODE = '''\
def turn_on(device: str) -> None:
    print(f"[{device} switched on]")


def turn_off(device: str) -> None:
    print(f"[{device} switched off]")
'''


def python_name(name: str) -> str:
    """class -> class_, print -> print_. Other names are unchanged."""
    return name + "_" if name in RESERVED_NAMES else name


def python_literal(value: int | float | str | bool) -> str:
    """A value written as Python source: True, 32.5, 'fan'."""
    if isinstance(value, bool):  # checked first: in Python, bool is a kind of int
        return "True" if value else "False"
    return repr(value)  # repr gives the Python source form, with quotes and escapes


class CodeGenerator:
    """Writes the Python program for one analyzed FlowLang Program."""

    def __init__(self, analysis: AnalysisResult):
        self.global_writes = analysis.global_writes
        # Functions and built-ins by name, to look up parameter types at calls.
        self.callables = {s.name: s for s in analysis.symbols if s.is_callable()}
        self.lines: list[str] = []
        self.indent = 0
        self.return_type: str | None = None  # of the function being generated

    def write(self, line: str = ""):
        self.lines.append(INDENT * self.indent + line if line else "")

    # ---- The whole program --------------------------------------------------

    def generate(self, program: Program) -> str:
        """Layout: header, built-ins, functions and events, then the main code."""
        self.write(f"# Generated by flowc, the FlowLang compiler, from program '{program.name}'.")
        self.write("# Edit the .flow source and compile again instead of changing this file.")
        self.write()
        self.write()
        self.lines.extend(BUILTINS_CODE.splitlines())

        declarations = [item for item in program.items if isinstance(item, (FunctionDecl, EventDecl))]
        statements = [item for item in program.items if not isinstance(item, (FunctionDecl, EventDecl))]

        # Functions and events go first, so they exist before the main code calls
        # them, even if the FlowLang source declares them further down.
        for declaration in declarations:
            self.write()
            self.write()
            if isinstance(declaration, FunctionDecl):
                self.function(declaration)
            else:
                self.event(declaration)

        self.write()
        self.write()
        self.write('if __name__ == "__main__":')
        self.indent += 1
        self.statements(statements)
        self.indent -= 1
        return "\n".join(self.lines) + "\n"

    def function(self, fn: FunctionDecl):
        params = ", ".join(f"{python_name(p.name)}: {PYTHON_TYPES[p.type]}" for p in fn.params)
        returns = PYTHON_TYPES[fn.return_type] if fn.return_type else "None"
        self.write(f"def {python_name(fn.name)}({params}) -> {returns}:")
        self.return_type = fn.return_type
        self.body(fn.name, fn.body)
        self.return_type = None

    def event(self, event: EventDecl):
        self.write(f"def {python_name(event.name)}() -> None:")
        self.body(event.name, event.body)

    def body(self, name: str, block: Block):
        """A function or event body, starting with `global` for globals it assigns."""
        self.indent += 1
        assigned_globals = sorted(self.global_writes.get(name, ()))
        if assigned_globals:
            self.write("global " + ", ".join(python_name(n) for n in assigned_globals))
        self.statements(block.statements)
        self.indent -= 1

    # ---- Statements ---------------------------------------------------------

    def block(self, block: Block):
        self.indent += 1
        self.statements(block.statements)
        self.indent -= 1

    def statements(self, statements: list[Statement]):
        if not statements:
            self.write("pass")  # Python does not allow an empty block
        for stmt in statements:
            self.statement(stmt)

    def statement(self, stmt: Statement):
        if isinstance(stmt, VarDecl):
            value = self.converted(stmt.value, stmt.type)
            self.write(f"{python_name(stmt.name)}: {PYTHON_TYPES[stmt.type]} = {value}")
        elif isinstance(stmt, Assign):
            self.write(f"{python_name(stmt.name)} = {self.converted(stmt.value, stmt.type)}")
        elif isinstance(stmt, IfStmt):
            self.if_statement(stmt, "if")
        elif isinstance(stmt, RepeatStmt):
            self.write(f"for _ in range({self.code(stmt.count)}):")
            self.block(stmt.body)
        elif isinstance(stmt, ReturnStmt):
            if stmt.value is None:
                self.write("return")
            else:
                self.write(f"return {self.converted(stmt.value, self.return_type)}")
        elif isinstance(stmt, EmitStmt):
            self.emit(stmt)
        elif isinstance(stmt, CallStmt):
            self.write(self.call(stmt.call))
        elif isinstance(stmt, TriggerStmt):
            self.write(f"{python_name(stmt.event)}()")
        else:
            raise TypeError(f"unknown statement {stmt!r}")

    def if_statement(self, stmt: IfStmt, keyword: str):
        """An if, with `else if` chains written as Python's elif."""
        self.write(f"{keyword} {self.code(stmt.condition)}:")
        self.block(stmt.then_block)
        if isinstance(stmt.else_branch, IfStmt):
            self.if_statement(stmt.else_branch, "elif")
        elif stmt.else_branch is not None:
            self.write("else:")
            self.block(stmt.else_branch)

    def emit(self, stmt: EmitStmt):
        value = self.code(stmt.value)
        if stmt.value.type == "bool":
            # FlowLang spells booleans true/false; Python would print True/False.
            self.write(f'print("true" if {value} else "false")')
        else:
            self.write(f"print({value})")

    # ---- Expressions --------------------------------------------------------

    def code(self, expr: Expression) -> str:
        """Python code for an expression."""
        return self.expression(expr)[0]

    def converted(self, expr: Expression, target_type: str) -> str:
        """Code for a value stored as target_type, converting int to float if needed."""
        if target_type == "float" and expr.type == "int":
            if isinstance(expr, Literal):
                return repr(float(expr.value))  # 2 -> 2.0
            return f"float({self.code(expr)})"
        return self.code(expr)

    def expression(self, expr: Expression) -> tuple[str, int]:
        """Python code for an expression, plus the precedence of its outermost operator.

        The parent uses the precedence to decide whether this code needs parentheses.
        """
        if isinstance(expr, Literal):
            return python_literal(expr.value), ATOM
        if isinstance(expr, Variable):
            return python_name(expr.name), ATOM
        if isinstance(expr, Call):
            return self.call(expr), ATOM
        if isinstance(expr, UnaryOp):
            return self.unary(expr)
        if isinstance(expr, BinaryOp):
            return self.binary(expr)
        raise TypeError(f"unknown expression {expr!r}")

    def call(self, call: Call) -> str:
        param_types = self.callables[call.name].params
        args = ", ".join(self.converted(arg, t) for arg, t in zip(call.args, param_types))
        return f"{python_name(call.name)}({args})"

    def unary(self, expr: UnaryOp) -> tuple[str, int]:
        operand, operand_precedence = self.expression(expr.operand)
        if expr.op == "!":
            precedence, text = NOT, "not "
        else:
            precedence, text = NEGATE, "-"
        if operand_precedence < precedence:
            operand = f"({operand})"
        return text + operand, precedence

    def binary(self, expr: BinaryOp) -> tuple[str, int]:
        precedence = BINARY_PRECEDENCE[expr.op]
        left, left_precedence = self.expression(expr.left)
        right, right_precedence = self.expression(expr.right)

        if expr.op == "^":
            # ** groups from the right, so a left side at the same level needs parentheses.
            left_needs_parens = left_precedence <= precedence
            right_needs_parens = right_precedence < precedence
        else:
            # Other operators group from the left, so a right side at the same level
            # needs parentheses: a - (b - c). Comparisons can't share a level at all,
            # because Python would chain them: a < b == c means a < b and b == c.
            left_needs_parens = left_precedence < precedence or (
                precedence == COMPARISON and left_precedence == COMPARISON
            )
            right_needs_parens = right_precedence <= precedence

        if left_needs_parens:
            left = f"({left})"
        if right_needs_parens:
            right = f"({right})"

        if expr.op == "/" and expr.type == "int":
            operator = "//"  # FlowLang int / int is integer division
        else:
            operator = PYTHON_OPERATORS.get(expr.op, expr.op)
        code = f"{left} {operator} {right}"

        if expr.op == "^" and expr.type == "int":
            # Python gives a float for a negative exponent (2 ** -1 == 0.5); FlowLang says int.
            return f"int({code})", ATOM
        return code, precedence


def generate(program: Program, analysis: AnalysisResult) -> str:
    """Convenience function: the Python source code for an analyzed program."""
    return CodeGenerator(analysis).generate(program)
